export type LocationCity = keyof typeof DISTRICT_SOURCE_BY_CITY;

function toTurkishDisplayName(value: string): string {
  const lower = value.toLocaleLowerCase("tr-TR");
  return lower.replace(/(^|[\s-])(\p{L})/gu, (_match, prefix: string, letter: string) =>
    `${prefix}${letter.toLocaleUpperCase("tr-TR")}`,
  );
}

const DISTRICTS_BY_CITY: Readonly<Record<LocationCity, readonly string[]>> = Object.fromEntries(
  Object.entries(DISTRICT_SOURCE_BY_CITY).map(([city, source]) => [
    city,
    source.split("|").map(toTurkishDisplayName),
  ]),
) as Record<LocationCity, readonly string[]>;

export const locationCities: readonly string[] = [
  "Tüm Türkiye",
  ...Object.keys(DISTRICT_SOURCE_BY_CITY),
];

export function getDistrictsForCity(city: string): readonly string[] {
  return DISTRICTS_BY_CITY[city as LocationCity] ?? [];
}

export function isLocationCity(city: string): city is LocationCity {
  return Object.hasOwn(DISTRICT_SOURCE_BY_CITY, city);
}

